package ifElse2;

public class Bai3 {
    public static void main(String[] args) {
        int x = 3500;
        int y = 250;

        if (x < 2000 || x > 3000) {
            System.out.println("Giá trị của x: " + x);
        }

        if (y >= 100 && y <= 500) {
            System.out.println("Giá trị của y: " + y);
        }
    }
}
